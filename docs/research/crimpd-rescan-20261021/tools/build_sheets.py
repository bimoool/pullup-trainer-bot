HF = PatternFill("solid", fgColor="E8EEF7"); BF = Font(bold=True)
def sheet(wb, title, header, rows, widths=None, dv=None):
    ws = wb.create_sheet(title); ws.append(header)
    for r in rows: ws.append(r)
    for c in ws[1]: c.font = BF; c.fill = HF; c.alignment = Alignment(wrap_text=True, vertical="top")
    for row in ws.iter_rows(min_row=2):
        for c in row: c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "B2"; ws.auto_filter.ref = ws.dimensions
    for i, h in enumerate(header):
        ws.column_dimensions[chr(65+i) if i < 26 else "A"+chr(65+i-26)].width = (widths or {}).get(i, 22)
    for col, vals in (dv or {}).items():
        v = DataValidation(type="list", formula1='"' + ",".join(vals) + '"', allow_blank=True)
        ws.add_data_validation(v); v.add(f"{col}2:{col}500")
    return ws
